import unittest
from unittest import mock

from htpolynet.core import projectfilesystem as pfs

LOG = 'htpolynet.core.projectfilesystem'


class TestShadowingIsAnnounced(unittest.TestCase):
    """A stale copy of a packaged file keeps its old version's settings for as long as
    it stays on the search path, and nothing used to say which file a run got.  An
    npt.mdp copied from 2.6.2 reverted LINCS to order 4 across four upgrades."""

    def note(self, packaged_exists, source='user library'):
        root = mock.MagicMock()
        root.joinpath.return_value.exists.return_value = packaged_exists
        lib = mock.MagicMock()
        lib._root = root
        with mock.patch.object(pfs, '_SYSTEM_LIBRARY_', lib):
            with self.assertLogs(LOG, level='WARNING') as cm:
                pfs._note_if_shadowing('mdp/npt.mdp', source)
                logger = __import__('logging').getLogger(LOG)
                logger.warning('sentinel')
            return '\n'.join(cm.output)

    def test_it_says_so_when_the_packaged_file_exists(self):
        msg = self.note(packaged_exists=True)
        self.assertIn('mdp/npt.mdp', msg)
        self.assertIn('replaces the copy', msg)
        self.assertIn('after any upgrade', msg)

    def test_it_is_silent_for_a_file_htpolynet_does_not_ship(self):
        msg = self.note(packaged_exists=False)
        self.assertNotIn('replaces the copy', msg)

    def test_it_names_which_source_the_file_came_from(self):
        self.assertIn('user cache', self.note(True, source='user cache'))

    def test_it_never_raises(self):
        # checkout must not fail because the warning could not be formed
        with mock.patch.object(pfs, '_SYSTEM_LIBRARY_', object()):
            pfs._note_if_shadowing('mdp/npt.mdp', 'user library')


class TestASmilesInputShadowsNothing(unittest.TestCase):
    """The SMILES generator writes into the user library, so its output came back as a
    user-library hit and drew the note seven log lines after htpolynet wrote it (v2.15.0
    sweep, example 0's STY.mol2).  For a SMILES constituent the packaged file is not what
    the run would otherwise use, so the note does not apply -- generated or kept."""

    def setUp(self):
        self.saved = set(pfs._SMILES_INPUTS_)
        pfs._SMILES_INPUTS_.clear()

    def tearDown(self):
        pfs._SMILES_INPUTS_.clear()
        pfs._SMILES_INPUTS_.update(self.saved)

    def note(self, filename):
        root = mock.MagicMock()
        root.joinpath.return_value.exists.return_value = True
        lib = mock.MagicMock()
        lib._root = root
        with mock.patch.object(pfs, '_SYSTEM_LIBRARY_', lib):
            with self.assertLogs(LOG, level='WARNING') as cm:
                pfs._note_if_shadowing(filename, 'user library')
                __import__('logging').getLogger(LOG).warning('sentinel')
            return '\n'.join(cm.output)

    def test_a_noted_smiles_input_is_silent(self):
        pfs.note_smiles_input('molecules/inputs/STY.mol2')
        self.assertNotIn('replaces the copy', self.note('molecules/inputs/STY.mol2'))

    def test_the_path_is_compared_normalized(self):
        pfs.note_smiles_input('molecules/inputs/STY.mol2')
        self.assertNotIn('replaces the copy', self.note('molecules//inputs/./STY.mol2'))

    def test_other_files_still_warn(self):
        pfs.note_smiles_input('molecules/inputs/STY.mol2')
        self.assertIn('replaces the copy', self.note('molecules/inputs/DVB.mol2'))
        self.assertIn('replaces the copy', self.note('mdp/npt.mdp'))


class TestAKeptSmilesFileIsReported(unittest.TestCase):
    """With the note gone for SMILES inputs, a kept mol2 -- possibly generated by an
    older version -- is the one way such a constituent runs on something other than its
    SMILES, so it is reported at INFO rather than DEBUG."""

    def test_keeping_an_existing_file_is_logged_at_info(self):
        import tempfile
        from htpolynet.external.smiles_input import materialize_smiles_inputs
        with tempfile.TemporaryDirectory() as d:
            open(f'{d}/STY.mol2', 'w').close()
            with self.assertLogs('htpolynet.external.smiles_input', level='INFO') as cm:
                got = materialize_smiles_inputs({'STY': {'smiles': 'C=Cc1ccccc1'}}, inputs_dir=d)
        self.assertEqual(got, [])
        self.assertTrue(any('using existing' in m and 'delete it' in m for m in cm.output))
